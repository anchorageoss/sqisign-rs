"""Bundle main.tex into one self-contained file for Overleaf.

main_standalone.tex = every \\input inlined (tables and the generated macro
files) and every CSV that pgfplots reads inlined as table data.  The
bibliography stays in refs.bib, uploaded next to it.  Regenerated by `make
figures`; edit main.tex or the repository documents, never this file.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
tex = (HERE / "main.tex").read_text(encoding="utf-8")


def inline_input(m):
    name = m.group(1)
    p = HERE / (name if name.endswith(".tex") else name + ".tex")
    body = p.read_text(encoding="utf-8").rstrip("\n")
    return f"% ---- begin {name}\n{body}\n% ---- end {name}"


for _ in range(3):
    tex = re.sub(r"\\input\{([^}]*)\}", inline_input, tex)


def inline_csv(m):
    p = HERE / m.group(1)
    rows = p.read_text(encoding="utf-8").strip("\n")
    return "{%\n" + rows + "\n}"


tex = re.sub(r"\{(figures/data/[^}]*\.csv)\}", inline_csv, tex)

header = (
    "% ============================================================\n"
    "% SINGLE-FILE VERSION for Overleaf, generated by figures/bundle.py\n"
    "% from main.tex, tables/ and figures/data/.  Do not edit: edit\n"
    "% main.tex (or the repository documents) and run `make figures` in\n"
    "% paper-dim4.  Upload refs.bib next to it.\n"
    "% ============================================================\n"
)
(HERE / "main_standalone.tex").write_text(header + tex, encoding="utf-8")
print("wrote main_standalone.tex")
