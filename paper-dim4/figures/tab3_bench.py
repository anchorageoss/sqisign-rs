"""Table 3: key generation, signing and verification in megacycles (medians
of the session), the C reference's broadwell build against the Rust code,
round 3 and round 2, dimension 2 and 4; the dimension-4 verifier's multiple
over the dimension-2 verifier of the same crate and round in its own
column.  Source: paper-dim4/BENCH.md, the paper's session."""
from session import *

L = ["I", "III", "V"]
f1 = lambda x: f"{x:.1f}"


def row(label, impl, rnd, dim, l, ref=None):
    k = (impl, rnd, dim, l)
    if (impl, rnd, dim, l, "keygen") not in BENCH:
        return None
    kg, sg, vf = (b(*k, op)["median"] for op in ("keygen", "sign", "verify from bytes"))
    mult = f"{vf / ref:.1f}" if ref else ""
    return f"{label} & {l} & {f1(kg)} & {f1(sg)} & {f1(vf)} & {mult} \\\\"


lines = ["% generated by figures/tab3_bench.py; do not edit",
         r"\begin{tabular}{@{}llrrrc@{}}", r"\toprule",
         r"implementation & level & keygen & sign & verify & $\times$ dim.\ 2 \\", r"\midrule"]
for rnd, C, R in ((3, C3, R3), (2, C2, R2)):
    lines.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{round-{rnd} primes}}}} \\\\")
    for l in L:
        r = row("C reference, dimension 2", C, rnd, 2, l)
        if r:
            lines.append(r)
    for l in L:
        lines.append(row("Rust, dimension 2", R, rnd, 2, l))
    if (R, rnd, 2, "I", "verify compressed from bytes") in BENCH:
        vf = b(R, rnd, 2, "I", "verify compressed from bytes")["median"]
        lines.append(f"Rust, dimension 2, compressed verify & I & & & {f1(vf)} & \\\\")
    ref = b(R, rnd, 2, "I", "verify from bytes")["median"]
    lines.append(row("Rust, dimension 4 (compact)", R, rnd, 4, "I", ref))
    if rnd == 3:
        lines.append(r"\addlinespace")
lines += [r"\bottomrule", r"\end{tabular}"]
write_table("tab3_bench", "\n".join(lines) + "\n")
